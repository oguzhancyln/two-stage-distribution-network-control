%% v4_figures.m
% Rebuilds Figures 5--8 from saved v4 consistent-Qmax results.
% IMPORTANT: This script does NOT rerun optimization.
%
% Required input files:
%   results_ablation_33_69_v4_consistent_qmax/ablation_results_33bus.mat
%   results_ablation_33_69_v4_consistent_qmax/ablation_results_69bus.mat
%
% Output folder:
%   results_test01c_consistent_qmax_envelopes/
%
% Main outputs expected by the current LaTeX file:
%   fig_33bus_condition_aware_voltage_envelope.png
%   fig_33bus_condition_aware_violation_count_per_step.png
%   fig_69bus_condition_aware_voltage_envelope.png
%   fig_69bus_condition_aware_violation_count_per_step.png

clear; clc; close all;

%% Paths
scriptFullPath = mfilename('fullpath');

if isempty(scriptFullPath)
    scriptDir = pwd;
else
    scriptDir = fileparts(scriptFullPath);
end

cfg.Vmin = 0.95;
cfg.Vmax = 1.05;

cfg.inputDir = fullfile( ...
    scriptDir, ...
    'results_ablation_33_69_v4_consistent_qmax');

cfg.outputDir = fullfile( ...
    scriptDir, ...
    'results_test01c_consistent_qmax_envelopesenson');

if ~exist(cfg.outputDir, 'dir')
    mkdir(cfg.outputDir);
end

systems = {'33bus', '69bus'};
allRows = table();

%% Create Figures 5--8
for s = 1:numel(systems)

    sysName = systems{s};

    inFile = fullfile( ...
        cfg.inputDir, ...
        sprintf('ablation_results_%s.mat', sysName));

    if ~exist(inFile, 'file')
        error(['Missing input file:\n  %s\n\n', ...
               'Run the v4 consistent-Qmax analysis first.'], ...
               inFile);
    end

    data = load(inFile);

    if ~isfield(data, 'result') || ...
       ~isfield(data.result, 'Vcase') || ...
       ~isfield(data.result.Vcase, 'NoControl') || ...
       ~isfield(data.result.Vcase, 'ProposedHybrid')

        error('Unexpected MAT-file structure in:\n  %s', inFile);
    end

    % Internal names retained from saved MAT files.
    % Visible labels used in the figures are updated below.
    Vref   = data.result.Vcase.NoControl;
    Vcoord = data.result.Vcase.ProposedHybrid;

    %% Summary metrics
    mRef   = computeMetricsLocal(Vref,   cfg.Vmin, cfg.Vmax);
    mCoord = computeMetricsLocal(Vcoord, cfg.Vmin, cfg.Vmax);

    Tsys = table();

    Tsys.System = {sysName; sysName};

    Tsys.Case = { ...
        'Reference operation'; ...
        'Coordinated strategy'};

    Tsys.MinV = [ ...
        mRef.MinV; ...
        mCoord.MinV];

    Tsys.MaxV = [ ...
        mRef.MaxV; ...
        mCoord.MaxV];

    Tsys.MeanV = [ ...
        mRef.MeanV; ...
        mCoord.MeanV];

    Tsys.TotalVoltageDeviation = [ ...
        mRef.TotalVoltageDeviation; ...
        mCoord.TotalVoltageDeviation];

    Tsys.UnderVoltageCount = [ ...
        mRef.UnderVoltageCount; ...
        mCoord.UnderVoltageCount];

    Tsys.OverVoltageCount = [ ...
        mRef.OverVoltageCount; ...
        mCoord.OverVoltageCount];

    Tsys.TotalViolationCount = [ ...
        mRef.TotalViolationCount; ...
        mCoord.TotalViolationCount];

    Tsys.DevReductionPercent = [ ...
        0; ...
        100 * ...
        (mRef.TotalVoltageDeviation - ...
         mCoord.TotalVoltageDeviation) / ...
        max(mRef.TotalVoltageDeviation, eps)];

    Tsys.ViolationReductionPercent = [ ...
        0; ...
        100 * ...
        (mRef.TotalViolationCount - ...
         mCoord.TotalViolationCount) / ...
        max(mRef.TotalViolationCount, eps)];

    allRows = [allRows; Tsys]; %#ok<AGROW>

    fprintf('\n%s summary:\n', systemLabelLocal(sysName));
    disp(Tsys);

    %% Plot voltage envelope: Figure 5 or Figure 7
    makeVoltageEnvelopeFigureLocal( ...
        sysName, Vref, Vcoord, cfg);

    %% Plot violation timeline: Figure 6 or Figure 8
    makeViolationFigureLocal( ...
        sysName, Vref, Vcoord, cfg);
end

%% Save summary CSV
writetable( ...
    allRows, ...
    fullfile(cfg.outputDir, ...
    'test01c_consistent_qmax_summary.csv'));

fprintf('\nDone. Figures 5--8 were saved under:\n  %s\n', ...
    cfg.outputDir);

%% ============================================================
%% Local functions
%% ============================================================

function m = computeMetricsLocal(V, Vmin, Vmax)

    under = max(Vmin - V, 0);
    over  = max(V - Vmax, 0);

    m.MinV = min(V(:));
    m.MaxV = max(V(:));
    m.MeanV = mean(V(:));

    m.TotalVoltageDeviation = ...
        sum((V(:) - 1).^2);

    m.UnderVoltageCount = ...
        nnz(under > 0);

    m.OverVoltageCount = ...
        nnz(over > 0);

    m.TotalViolationCount = ...
        m.UnderVoltageCount + ...
        m.OverVoltageCount;
end

function makeVoltageEnvelopeFigureLocal( ...
    sysName, Vref, Vcoord, cfg)

    t = 1:size(Vref, 1);

    refMin   = min(Vref,   [], 2);
    refMax   = max(Vref,   [], 2);

    coordMin = min(Vcoord, [], 2);
    coordMax = max(Vcoord, [], 2);

    fig = figure( ...
        'Color', 'w', ...
        'Position', [100 100 900 600], ...
        'MenuBar', 'none', ...
        'ToolBar', 'none');

    ax = axes(fig);

    hold(ax, 'on');
    grid(ax, 'on');
    box(ax, 'on');

    plot(ax, t, refMin, ...
        '--', ...
        'LineWidth', 1.8);

    plot(ax, t, refMax, ...
        '--', ...
        'LineWidth', 1.8);

    plot(ax, t, coordMin, ...
        '-', ...
        'LineWidth', 2.2);

    plot(ax, t, coordMax, ...
        '-', ...
        'LineWidth', 2.2);

    yline(ax, cfg.Vmin, ...
        ':', ...
        'V_{min}', ...
        'LineWidth', 1.2, ...
        'LabelHorizontalAlignment', 'right');

    yline(ax, cfg.Vmax, ...
        ':', ...
        'V_{max}', ...
        'LineWidth', 1.2, ...
        'LabelHorizontalAlignment', 'right');

    xlabel(ax, 'Time step');

    ylabel(ax, ...
        'Voltage magnitude (p.u.)');

    title(ax, ...
        sprintf( ...
        '%s minimum and maximum voltage profiles', ...
        systemLabelLocal(sysName)));

    legend(ax, { ...
        'Reference min', ...
        'Reference max', ...
        'Coordinated min', ...
        'Coordinated max'}, ...
        'Location', 'best');

    ylim(ax, [ ...
        min([refMin; coordMin; cfg.Vmin]) - 0.02, ...
        max([refMax; coordMax; cfg.Vmax]) + 0.02]);

    removeAxesToolbarLocal(ax);

    base = fullfile( ...
        cfg.outputDir, ...
        sprintf( ...
        'fig_%s_condition_aware_voltage_envelope', ...
        sysName));

    savefig(fig, [base '.fig']);

    exportgraphics( ...
        fig, ...
        [base '.png'], ...
        'Resolution', 300);

    close(fig);
end

function makeViolationFigureLocal( ...
    sysName, Vref, Vcoord, cfg)

    t = 1:size(Vref, 1);

    refViol = ...
        sum(Vref < cfg.Vmin | ...
            Vref > cfg.Vmax, 2);

    coordViol = ...
        sum(Vcoord < cfg.Vmin | ...
            Vcoord > cfg.Vmax, 2);

    fig = figure( ...
        'Color', 'w', ...
        'Position', [100 100 900 600], ...
        'MenuBar', 'none', ...
        'ToolBar', 'none');

    ax = axes(fig);

    hold(ax, 'on');
    grid(ax, 'on');
    box(ax, 'on');

    plot(ax, t, refViol, ...
        '--', ...
        'LineWidth', 1.8);

    plot(ax, t, coordViol, ...
        '-', ...
        'LineWidth', 2.2);

    xlabel(ax, 'Time step');

    ylabel(ax, ...
        'Number of violating buses');

    title(ax, ...
        sprintf( ...
        '%s voltage-limit violations', ...
        systemLabelLocal(sysName)));

    legend(ax, { ...
        'Reference operation', ...
        'Coordinated strategy'}, ...
        'Location', 'best');

    ylim(ax, [ ...
        0, ...
        max([refViol; coordViol]) + 2]);

    removeAxesToolbarLocal(ax);

    base = fullfile( ...
        cfg.outputDir, ...
        sprintf( ...
        'fig_%s_condition_aware_violation_count_per_step', ...
        sysName));

    savefig(fig, [base '.fig']);

    exportgraphics( ...
        fig, ...
        [base '.png'], ...
        'Resolution', 300);

    close(fig);
end

function removeAxesToolbarLocal(ax)

    try
        disableDefaultInteractivity(ax);
    catch
    end

    try
        axtoolbar(ax, {});
    catch
    end
end

function label = systemLabelLocal(sysName)

    switch lower(sysName)

        case '33bus'
            label = '33-bus';

        case '69bus'
            label = '69-bus';

        otherwise
            label = sysName;
    end
end